package shop.auth.service.twoFa;

import dev.samstevens.totp.code.HashingAlgorithm;
import dev.samstevens.totp.exceptions.QrGenerationException;
import dev.samstevens.totp.qr.QrData;
import dev.samstevens.totp.qr.QrGenerator;
import dev.samstevens.totp.qr.ZxingPngQrGenerator;
import dev.samstevens.totp.secret.DefaultSecretGenerator;
import dev.samstevens.totp.secret.SecretGenerator;
import org.springframework.stereotype.Service;

import static dev.samstevens.totp.util.Utils.getDataUriForImage;

@Service
public class TotpSetupService {

    private SecretGenerator secretGenerator = new DefaultSecretGenerator();
    private QrGenerator qrGenerator = new ZxingPngQrGenerator();


    //By default, this class generates secrets that are 32 characters long
    public String createSecrete(){
        return secretGenerator.generate();
    }

    public String createQrCode(String secret, String email){
        QrData data = new QrData.Builder()
                .label(email)
                .secret(secret)
                .issuer("I_Love_Shopping")
                .algorithm(HashingAlgorithm.SHA1)
                .digits(6)
                .period(30)
                .build();

        try{

            byte[] imageData= qrGenerator.generate(data);

            //The generate method returns a byte array of the raw image data. The mime type of the data
            // that is generated by the generator can be retrieved using the getImageMimeType method.
            return getDataUriForImage(imageData, qrGenerator.getImageMimeType());

            //todo for frontend (<img th:src="${dataUri}" />)  Documentation - https://github.com/samdjstevens/java-totp/blob/master/README.md#generating-a-qr-code
        } catch (QrGenerationException e) {
            throw new RuntimeException("QR Generation failed",e);
        }
    }

}
