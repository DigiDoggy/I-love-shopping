import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.ToString;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import org.jboss.aerogear.security.otp.api.Base32;
import shop.auth.enums.Roles;

import java.time.Instant;
import java.util.List;
import java.util.UUID;

@Entity
@Table(name = "users")
@Data
@NoArgsConstructor
@AllArgsConstructor
public class User {
    @Id
    //id generated by DB
    @GeneratedValue
    @JdbcTypeCode(SqlTypes.UUID)
    private UUID id;
    @Column(nullable = false, unique = true)
    private String email;
    @Column(name = "user_name", nullable = false)
    private String userName;
    @ToString.Exclude
    @Column(name = "password_hash", nullable = false)
    private String passwordHash;
    @Column(name = "phone_country_code", nullable = false)
    private String phoneCountryCode;
    @Column(name = "phone_number", nullable = false, unique = true)
    private String phoneNumber;
    @Column(name = "user_role", nullable = false)
    @Enumerated(EnumType.STRING)
    private Roles roles;
    @Column(name = "is_2fa_enabled", nullable = false)
    private boolean twoFaEnabled;
    @Column(name = "totp_secret")
    private String twoFaSecret;
    @Column(name = "created_at")
    private Instant createdAt = Instant.now();
    //todo need to check if it is needed, then create some massage for user about email verification
    @Column(name = "email_verified", nullable = false)
    private boolean emailVerified = false;


    private String generateTwoFaSecret() {
        return Base32.random();
    }
    //todo create fields earlier
    // and rewrite then UserPrincipal

//    @Column(name="enabled", nullable=false)
//    private boolean enabled = false;
//
//    @Column(name="account_non_locked", nullable=false)
//    private boolean accountNonLocked = true;
//
//    @Column(name="account_non_expired", nullable=false)
//    private boolean accountNonExpired = true;
//
//    @Column(name="credentials_non_expired", nullable=false)
//    private boolean credentialsNonExpired = true;

    @OneToMany(mappedBy = "user", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<Address> addresses;
    @OneToMany(mappedBy = "user", fetch = FetchType.LAZY)
    @ToString.Exclude
    private List<OauthAccount> oauthAccounts;
    @OneToMany(mappedBy = "user")
    @ToString.Exclude
    private List<Token> tokens;
}
